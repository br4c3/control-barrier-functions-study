def solve_with_available_solver(problem):
    installed = cp.installed_solvers()

    if "CLARABEL" in installed:
        problem.solve(solver=cp.CLARABEL, verbose=False)
        return "CLARABEL"

    if "SCS" in installed:
        problem.solve(
            solver=cp.SCS,
            verbose=False,
            max_iters=50000,
            eps=1e-4,
        )
        return "SCS"

    problem.solve(verbose=False)
    return "CVXPY default"


# =============================================================================
# 12. SUCCESSIVE CONVEXIFICATION
# =============================================================================

# Two-stage solve:
#   1) feasibility restoration: drive dynamics/landing slacks toward zero
#   2) fuel optimization: minimize propellant while keeping slacks near zero
FEASIBILITY_ITERS = 8
FUEL_ITERS = MAX_SCP_ITER - FEASIBILITY_ITERS

R_solution = None
V_solution = None
T_solution = None
M_solution = None
SIGMA_solution = None
NU_solution = None
LAST_SLACKS = None


def build_scp_problem(mode, iteration, trust_multiplier=1.0, hard_landing=False):
    """Construct one convex SCP subproblem."""

    # Decision variables.
    R = cp.Variable((3, N + 1))
    V = cp.Variable((3, N + 1))
    THRUST = cp.Variable((3, N))
    MASS = cp.Variable(N + 1)
    SIGMA = cp.Variable(N, nonneg=True)
    NU = cp.Variable((3, N))

    # Soft feasibility variables for descent/terminal constraints.
    nd = N - K_DESCENT_START + 1
    S_CONE = cp.Variable(nd, nonneg=True)          # km
    S_SPEED = cp.Variable(nd, nonneg=True)         # km/s
    S_ALT = cp.Variable(nd, nonneg=True)           # km
    S_TERMINAL = cp.Variable(nd, nonneg=True)      # km/s
    S_TOUCH_POS = cp.Variable(nonneg=True)          # km
    S_TOUCH_SPEED = cp.Variable(nonneg=True)        # km/s
    S_TOUCH_HORIZ = cp.Variable(nonneg=True)        # km/s

    constraints = [
        R[:, 0] == r0,
        V[:, 0] == v0,
        MASS[0] == MASS_INITIAL,
        MASS >= MASS_DRY,
        MASS <= MASS_INITIAL,
    ]

    virtual_dv_cost = 0
    thrust_smooth_cost = 0
    propellant_cost_kg = 0

    # Do not aggressively shrink the trust region during feasibility recovery.
    if mode == "feasibility":
        trust_scale = 1.0
    else:
        fuel_iter = max(0, iteration - FEASIBILITY_ITERS)
        trust_scale = max(0.45, 0.90**fuel_iter)

    trust_scale *= trust_multiplier

    # -------------------------------------------------------------------------
    # Dynamics, thrust, propellant and phase controls.
    # -------------------------------------------------------------------------
    for k in range(N):
        dt = DT[k]
        t_k = TIME[k]

        # Linearized gravity.
        g_ref, J_ref = gravity_and_jacobian(r_ref[:, k], t_k)
        g_linear = g_ref + J_ref @ (R[:, k] - r_ref[:, k])

        # Linearized T/m.
        mbar = max(float(mass_ref[k]), MASS_DRY + 100.0)
        tbar = thrust_ref[:, k]
        thrust_acc_linear = (
            THRUST[:, k] / mbar
            - (tbar / (mbar**2)) * (MASS[k] - mbar)
        )

        acceleration = g_linear + thrust_acc_linear + NU[:, k]

        constraints += [
            R[:, k + 1]
            == R[:, k] + dt * V[:, k] + 0.5 * dt**2 * acceleration,
            V[:, k + 1] == V[:, k] + dt * acceleration,
        ]

        # Thrust norm epigraph.
        constraints += [cp.norm(THRUST[:, k], 2) <= SIGMA[k]]

        # Propellant mass flow plus a fixed dry-hardware stage separation.
        propellant_k = dt * SIGMA[k] / (phase_isp(k) * G0)
        stage_drop_k = (
            STAGE_DROP_AT_DESCENT if k == K_DESCENT_START - 1 else 0.0
        )
        constraints += [
            MASS[k + 1] == MASS[k] - propellant_k - stage_drop_k
        ]
        propellant_cost_kg += propellant_k

        # Max thrust / max proper acceleration.
        tmax = phase_tmax(k)
        amax = phase_amax(k)
        constraints += [SIGMA[k] <= tmax]
        if amax > 0.0:
            constraints += [SIGMA[k] <= amax * MASS[k]]

        # Engine phase constraints.
        if k < K_TLI_START:
            constraints += [THRUST[:, k] == 0, SIGMA[k] == 0]

        elif k < K_TRANSFER_START:
            axis = v_ref[:, k] / max(np.linalg.norm(v_ref[:, k]), 1e-12)
            constraints += [
                axis @ THRUST[:, k] >= TMIN_TLI,
                axis @ THRUST[:, k] >= np.cos(GIMBAL_TLI) * SIGMA[k],
            ]

        elif k < K_DESCENT_START:
            # MCC engine may be completely off.
            pass

        else:
            # Powered descent.  Keep the scheduled engine-on lower bound small
            # enough that feasibility is not destroyed early in SCP.
            constraints += [
                n_land @ THRUST[:, k] >= TMIN_DESCENT,
                n_land @ THRUST[:, k]
                >= np.cos(GIMBAL_DESCENT) * SIGMA[k],
            ]

        # Slew rate only inside a continuous phase, not across ignition/cutoff.
        if k > 0:
            same_tli = K_TLI_START < k < K_TRANSFER_START
            same_mcc = K_TRANSFER_START < k < K_DESCENT_START
            same_descent = k > K_DESCENT_START

            if same_tli:
                slew = SLEW_TLI
            elif same_mcc:
                slew = SLEW_MCC
            elif same_descent:
                slew = SLEW_DESCENT
            else:
                slew = None

            if slew is not None:
                dt_slew = min(DT[k - 1], DT[k])
                constraints += [
                    cp.norm(THRUST[:, k] - THRUST[:, k - 1], 2)
                    <= slew * dt_slew
                ]

        # SCP trust regions. Mass trust was intentionally removed because the
        # original artificial mass reference was a major infeasibility source.
        if k <= K_TLI_START:
            r_trust = 2000.0 * trust_scale
            v_trust = 2.0 * trust_scale + 0.5
        elif k < K_DESCENT_START:
            r_trust = 160000.0 * trust_scale
            v_trust = 8.0 * trust_scale + 1.0
        else:
            r_trust = 12000.0 * trust_scale
            v_trust = 4.0 * trust_scale + 0.5

        constraints += [
            cp.norm(R[:, k] - r_ref[:, k], 2) <= r_trust,
            cp.norm(V[:, k] - v_ref[:, k], 2) <= v_trust,
        ]

        virtual_dv_cost += cp.norm(NU[:, k], 2) * dt
        if k > 0:
            thrust_smooth_cost += cp.norm(
                THRUST[:, k] - THRUST[:, k - 1], 2
            )

    # Terminal trust region around an already landing-feasible reference.
    constraints += [
        cp.norm(R[:, N] - r_ref[:, N], 2) <= 5000.0 * trust_scale + 50.0
    ]

    # -------------------------------------------------------------------------
    # Earth parking-orbit environment.
    # -------------------------------------------------------------------------
    for k in range(N_PARK + 1):
        rhat = r_ref[:, k] / np.linalg.norm(r_ref[:, k])
        that = v_ref[:, k] / max(np.linalg.norm(v_ref[:, k]), 1e-12)
        v_circ = np.sqrt(MU_E / np.linalg.norm(r_ref[:, k]))

        constraints += [
            rhat @ R[:, k] >= R_E + LEO_ALT_MIN,
            cp.norm(R[:, k], 2) <= R_E + LEO_ALT_MAX,
            that @ V[:, k] >= v_circ - 0.50,
            cp.norm(V[:, k], 2) <= v_circ + 0.50,
        ]

    # Broad inertial speed bound.
    for k in range(K_TLI_START, K_DESCENT_START + 1):
        constraints += [cp.norm(V[:, k], 2) <= MAX_EARTH_INERTIAL_SPEED]

    # Earth collision avoidance near Earth.
    for k in range(N_PARK + 1, N + 1):
        if np.linalg.norm(r_ref[:, k]) < 50000.0:
            rhat = r_ref[:, k] / np.linalg.norm(r_ref[:, k])
            constraints += [rhat @ R[:, k] >= R_E + 100.0]

    # Moon surface avoidance, linearized about reference.
    for k in range(N + 1):
        r_moon_k, _ = moon_state(TIME[k])
        d_ref = r_ref[:, k] - r_moon_k
        d_norm = np.linalg.norm(d_ref)

        if d_norm < 80000.0:
            dhat = d_ref / max(d_norm, 1e-12)
            if k < K_DESCENT_START:
                clearance = 20.0
            else:
                frac = (k - K_DESCENT_START) / max(1, N - K_DESCENT_START)
                clearance = 20.0 * (1.0 - frac)

            constraints += [
                dhat @ (R[:, k] - r_moon_k) >= R_M + clearance
            ]

    # -------------------------------------------------------------------------
    # Descent gate.
    # -------------------------------------------------------------------------
    r_moon_gate, v_moon_gate = moon_state(TIME[K_DESCENT_START])
    r_land_gate = r_moon_gate + R_M * n_land
    delta_gate = R[:, K_DESCENT_START] - r_land_gate
    gate_altitude = n_land @ delta_gate

    constraints += [
        cp.norm(R[:, K_DESCENT_START] - r_moon_gate, 2) <= R_M + 650.0,
        gate_altitude >= DESCENT_GATE_ALT_MIN,
        gate_altitude <= DESCENT_GATE_ALT_MAX,
        cp.norm(V[:, K_DESCENT_START] - v_moon_gate, 2)
        <= DESCENT_GATE_SPEED_MAX,
    ]

    # -------------------------------------------------------------------------
    # Lunar descent with soft feasibility restoration.
    # -------------------------------------------------------------------------
    for j, k in enumerate(range(K_DESCENT_START, N + 1)):
        frac = (k - K_DESCENT_START) / max(1, N - K_DESCENT_START)
        r_moon_k, v_moon_k = moon_state(TIME[k])
        r_land_k = r_moon_k + R_M * n_land

        delta_r = R[:, k] - r_land_k
        altitude = n_land @ delta_r
        horizontal_error = P_HORIZONTAL @ delta_r
        v_rel = V[:, k] - v_moon_k
        vertical_speed = n_land @ v_rel

        vmax_rel = 2.5 * (1.0 - frac)**1.3 + 0.030

        constraints += [
            cp.norm(v_rel, 2) <= vmax_rel + S_SPEED[j],
            altitude >= -S_ALT[j],
            cp.norm(horizontal_error, 2)
            <= np.tan(LANDING_CONE_ANGLE) * altitude + S_CONE[j],
            # Powered descent may hover, but it may never climb away from the
            # surface.  This removes the descend-rise-descend solution that an
            # altitude lower bound alone still permits.
            vertical_speed <= 0.0,
        ]

        if k < N:
            r_moon_next, _ = moon_state(TIME[k + 1])
            r_land_next = r_moon_next + R_M * n_land
            altitude_next = n_land @ (R[:, k + 1] - r_land_next)
            constraints += [altitude_next <= altitude]

        if frac >= 0.75:
            horizontal_speed = P_HORIZONTAL @ v_rel
            terminal_frac = (frac - 0.75) / 0.25
            max_down_speed = (
                0.080 * (1.0 - terminal_frac) + TOUCHDOWN_SPEED_MAX
            )
            max_horizontal = (
                0.050 * (1.0 - terminal_frac) + TOUCHDOWN_HORIZONTAL_MAX
            )

            constraints += [
                vertical_speed <= TOUCHDOWN_SPEED_MAX + S_TERMINAL[j],
                vertical_speed >= -max_down_speed - S_TERMINAL[j],
                cp.norm(horizontal_speed, 2)
                <= max_horizontal + S_TERMINAL[j],
                # Near the surface, allowable lateral speed collapses toward
                # the touchdown limit instead of permitting a long low hover
                # or sideways crawl.
                cp.norm(horizontal_speed, 2)
                <= (
                    TOUCHDOWN_HORIZONTAL_MAX
                    + LOW_ALT_HORIZONTAL_SPEED_SLOPE * altitude
                    + S_TERMINAL[j]
                ),
            ]

        if frac >= TERMINAL_CONE_START_FRACTION:
            constraints += [
                cp.norm(horizontal_error, 2)
                <= (
                    np.tan(TERMINAL_LANDING_CONE_ANGLE) * altitude
                    + S_CONE[j]
                )
            ]

    # -------------------------------------------------------------------------
    # Touchdown: soft during restoration, optionally exact during polishing.
    # -------------------------------------------------------------------------
    v_touch_rel = V[:, N] - v_moon_final

    if hard_landing:
        constraints += [
            R[:, N] == r_land_final,
            cp.norm(v_touch_rel, 2) <= TOUCHDOWN_SPEED_MAX,
            cp.norm(P_HORIZONTAL @ v_touch_rel, 2)
            <= TOUCHDOWN_HORIZONTAL_MAX,
            n_land @ v_touch_rel <= 0.0,
            cp.norm(v_touch_rel - v_touch_target, 2)
            <= TOUCHDOWN_TARGET_TOL,
            S_CONE == 0,
            S_SPEED == 0,
            S_ALT == 0,
            S_TERMINAL == 0,
            S_TOUCH_POS == 0,
            S_TOUCH_SPEED == 0,
            S_TOUCH_HORIZ == 0,
        ]
    else:
        constraints += [
            cp.norm(R[:, N] - r_land_final, 2) <= 0.050 + S_TOUCH_POS,
            cp.norm(v_touch_rel, 2)
            <= TOUCHDOWN_SPEED_MAX + S_TOUCH_SPEED,
            cp.norm(P_HORIZONTAL @ v_touch_rel, 2)
            <= TOUCHDOWN_HORIZONTAL_MAX + S_TOUCH_HORIZ,
            n_land @ v_touch_rel <= S_TOUCH_SPEED,
            cp.norm(v_touch_rel - v_touch_target, 2)
            <= TOUCHDOWN_TARGET_TOL + S_TOUCH_SPEED,
        ]

    # -------------------------------------------------------------------------
    # Objective.
    # -------------------------------------------------------------------------
    # Dimensionally normalized feasibility score.
    landing_slack_cost = (
        cp.sum(S_CONE) / 10.0
        + cp.sum(S_ALT) / 10.0
        + cp.sum(S_SPEED) / 0.05
        + cp.sum(S_TERMINAL) / 0.02
        + S_TOUCH_POS / 0.05
        + S_TOUCH_SPEED / 0.002
        + S_TOUCH_HORIZ / 0.0015
    )

    tracking_cost = cp.sum_squares((R - r_ref) / D_EM)

    if mode == "feasibility":
        objective = cp.Minimize(
            5.0e4 * virtual_dv_cost
            + 2.0e3 * landing_slack_cost
            + 1.0e-4 * thrust_smooth_cost
            + 1.0e-2 * tracking_cost
            + 1.0e-5 * propellant_cost_kg
        )
    else:
        objective = cp.Minimize(
            propellant_cost_kg / 1000.0
            + 1.0e5 * virtual_dv_cost
            + 5.0e3 * landing_slack_cost
            + 1.0e-4 * thrust_smooth_cost
            + 1.0e-2 * tracking_cost
        )

    problem = cp.Problem(objective, constraints)

    variables = dict(
        R=R,
        V=V,
        THRUST=THRUST,
        MASS=MASS,
        SIGMA=SIGMA,
        NU=NU,
        S_CONE=S_CONE,
        S_SPEED=S_SPEED,
        S_ALT=S_ALT,
        S_TERMINAL=S_TERMINAL,
        S_TOUCH_POS=S_TOUCH_POS,
        S_TOUCH_SPEED=S_TOUCH_SPEED,
        S_TOUCH_HORIZ=S_TOUCH_HORIZ,
        propellant_cost_kg=propellant_cost_kg,
    )

    return problem, variables


def read_slack_metrics(var):
    return {
        "cone_km": float(np.max(np.asarray(var["S_CONE"].value))),
        "speed_mps": float(np.max(np.asarray(var["S_SPEED"].value))) * 1000.0,
        "alt_km": float(np.max(np.asarray(var["S_ALT"].value))),
        "terminal_mps": float(np.max(np.asarray(var["S_TERMINAL"].value))) * 1000.0,
        "touch_pos_m": float(var["S_TOUCH_POS"].value) * 1000.0,
        "touch_speed_mps": float(var["S_TOUCH_SPEED"].value) * 1000.0,
        "touch_horiz_mps": float(var["S_TOUCH_HORIZ"].value) * 1000.0,
    }


def solve_one_scp_iteration(iteration, mode, hard_landing=False):
    """Retry automatically with a larger trust region if needed."""
    retry_scales = [1.0, 2.5, 6.0]

    for retry, trust_multiplier in enumerate(retry_scales, start=1):
        problem, var = build_scp_problem(
            mode=mode,
            iteration=iteration,
            trust_multiplier=trust_multiplier,
            hard_landing=hard_landing,
        )

        print(
            f"  attempt {retry}: mode={mode}, hard={hard_landing}, "
            f"trust x{trust_multiplier:.1f}"
        )
        print("  DCP:", problem.is_dcp())
        if not problem.is_dcp():
            raise RuntimeError("Convex SCP subproblem is not DCP-compliant.")

        try:
            solver_used = solve_with_available_solver(problem)
        except cp.error.SolverError:
            solver_used = "solver error"

        print("  Solver:", solver_used)
        print("  Status:", problem.status)
        print("  Objective:", problem.value)

        if problem.status in (cp.OPTIMAL, cp.OPTIMAL_INACCURATE):
            return problem, var

    return None, None


