"""
Apollo-like Earth-orbit -> Moon landing optimal control with CVXPY + SCP.

Main improvements over an impulsive Delta-V model
-------------------------------------------------
1) Continuous thrust vector T[k] [kN] is the control input.
2) Spacecraft mass M[k] [kg] is an optimization state.
3) Propellant is consumed from thrust magnitude using Isp.
4) Phase-dependent thrust limits, minimum throttle and gimbal cone.
5) Maximum acceleration constraint.
6) Thrust slew-rate constraint.
7) Earth parking-orbit environment.
8) Moon-relative approach/descent speed limits.
9) Lunar surface clearance, landing cone and touchdown constraints.
10) Nonlinear gravity and T/m are handled by successive convexification (SCP).

This is an educational Apollo-like model, not a historical Apollo reconstruction.
The solver uses feasibility restoration before fuel minimization to avoid premature infeasibility.
The Moon ephemeris is approximated by a circular inclined orbit and the vehicle is
represented as one equivalent spacecraft/propulsion system.

Units
-----
position     km
velocity     km/s
acceleration km/s^2
mass         kg
thrust       kN   (numerically kg*km/s^2)
time         s
"""

