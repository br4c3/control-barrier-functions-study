# Descent gate.
DESCENT_GATE_ALT_MIN = 50.0            # km
DESCENT_GATE_ALT_MAX = 500.0           # km
DESCENT_GATE_SPEED_MAX = 2.5           # km/s Moon-relative

# SCP parameters.
MAX_SCP_ITER = 22
REFERENCE_UPDATE_ALPHA = 0.55
VIRTUAL_DV_TOL = 1.0e-2                # km/s integrated virtual acceleration
TRAJECTORY_CHANGE_TOL = 10.0           # km RMS
MASS_CHANGE_TOL = 20.0                  # kg RMS


# =============================================================================
# 5. MOON MODEL
# =============================================================================

OMEGA_MOON = np.sqrt((MU_E + MU_M) / D_EM**3)
PHI_ARRIVAL = np.deg2rad(170.0)
PHI_0 = PHI_ARRIVAL - OMEGA_MOON * T_TOTAL


def moon_state(t):
    """Circular inclined Moon orbit in Earth-centered inertial coordinates."""
    theta = PHI_0 + OMEGA_MOON * t
    c = np.cos(theta)
    s = np.sin(theta)
    ci = np.cos(MOON_INCLINATION)
    si = np.sin(MOON_INCLINATION)

    r = D_EM * np.array([c, s * ci, s * si])
    v = D_EM * OMEGA_MOON * np.array([-s, c * ci, c * si])
    return r, v


# =============================================================================
# 6. GRAVITY + JACOBIAN
# =============================================================================


def point_gravity(r, center, mu):
    d = r - center
    rho = np.linalg.norm(d)
    return -mu * d / rho**3


def point_gravity_jacobian(r, center, mu):
    d = r - center
    rho = np.linalg.norm(d)
    I = np.eye(3)
    return -mu * (I / rho**3 - 3.0 * np.outer(d, d) / rho**5)


def gravity(r, t):
    r_moon, _ = moon_state(t)
    return (
        point_gravity(r, np.zeros(3), MU_E)
        + point_gravity(r, r_moon, MU_M)
    )


def gravity_and_jacobian(r, t):
    r_moon, _ = moon_state(t)

    g_e = point_gravity(r, np.zeros(3), MU_E)
    J_e = point_gravity_jacobian(r, np.zeros(3), MU_E)

    g_m = point_gravity(r, r_moon, MU_M)
    J_m = point_gravity_jacobian(r, r_moon, MU_M)

    return g_e + g_m, J_e + J_m


# =============================================================================
# 7. INITIAL EARTH PARKING ORBIT
# =============================================================================

R_LEO = R_E + LEO_ALT
V_LEO = np.sqrt(MU_E / R_LEO)
N_LEO = np.sqrt(MU_E / R_LEO**3)

r0 = np.array([R_LEO, 0.0, 0.0])
v0 = V_LEO * np.array([
    0.0,
    np.cos(LEO_INCLINATION),
    np.sin(LEO_INCLINATION),
])


def parking_orbit_state(t):
    theta = N_LEO * t
    c = np.cos(theta)
    s = np.sin(theta)
    ci = np.cos(LEO_INCLINATION)
    si = np.sin(LEO_INCLINATION)

    r = R_LEO * np.array([c, s * ci, s * si])
    v = V_LEO * np.array([-s, c * ci, c * si])
    return r, v


# =============================================================================
# 8. LANDING GEOMETRY
# =============================================================================

r_moon_final, v_moon_final = moon_state(T_TOTAL)
e_moon = r_moon_final / np.linalg.norm(r_moon_final)

# Near-side landing-site outward normal.
n_land = -e_moon

z_axis = np.array([0.0, 0.0, 1.0])
t_land = np.cross(z_axis, n_land)
if np.linalg.norm(t_land) < 1e-8:
    t_land = np.cross(np.array([0.0, 1.0, 0.0]), n_land)
t_land /= np.linalg.norm(t_land)

P_HORIZONTAL = np.eye(3) - np.outer(n_land, n_land)
r_land_final = r_moon_final + R_M * n_land
v_touch_target = (
    -TOUCHDOWN_DOWN_TARGET * n_land
    + TOUCHDOWN_LATERAL_TARGET * t_land
)


# =============================================================================
# 9. PHASE PARAMETER HELPERS
# =============================================================================


def phase_isp(k):
    if K_TLI_START <= k < K_TRANSFER_START:
        return ISP_TLI
    if K_TRANSFER_START <= k < K_DESCENT_START:
        return ISP_MCC
    if k >= K_DESCENT_START:
        return ISP_DESCENT
    return ISP_TLI


def phase_tmax(k):
    if k < K_TLI_START:
        return 0.0
    if k < K_TRANSFER_START:
        return TMAX_TLI
    if k < K_DESCENT_START:
        return TMAX_MCC
    return TMAX_DESCENT


def phase_amax(k):
    if k < K_TLI_START:
        return 0.0
    if k < K_TRANSFER_START:
        return AMAX_TLI
    if k < K_DESCENT_START:
        return AMAX_MCC
    return AMAX_DESCENT


# =============================================================================
# 10. INITIAL SCP REFERENCE
# =============================================================================


def cubic_bezier(p0, p1, p2, p3, s):
    return (
        (1.0 - s)**3 * p0
        + 3.0 * (1.0 - s)**2 * s * p1
        + 3.0 * (1.0 - s) * s**2 * p2
        + s**3 * p3
    )


def smoothstep5(s):
    """0 -> 1 with zero first/second derivative at both ends."""
    s = np.clip(s, 0.0, 1.0)
    return 10.0 * s**3 - 15.0 * s**4 + 6.0 * s**5


def smoothstep5_derivative(s):
    s = np.clip(s, 0.0, 1.0)
    return 30.0 * s**2 * (1.0 - s)**2


def make_initial_reference():
    """
    Build an SCP reference that is intentionally feasible with respect to the
    landing cone geometry and has zero Moon-relative terminal velocity.

    The reference does NOT need to satisfy the nonlinear dynamics exactly;
    virtual control handles that during the feasibility iterations.
    """
    r_ref = np.zeros((3, N + 1))
    v_ref = np.zeros((3, N + 1))
    thrust_ref = np.zeros((3, N))
    mass_ref = np.full(N + 1, MASS_INITIAL, dtype=float)

    # -------------------------------------------------------------------------
    # A) Circular LEO reference.
    # -------------------------------------------------------------------------
    for k in range(N_PARK + 1):
        r_ref[:, k], v_ref[:, k] = parking_orbit_state(TIME[k])

    # -------------------------------------------------------------------------
    # B) Finite TLI reference propagation.
    # -------------------------------------------------------------------------
    # 350 kN is enough to create a useful departure reference without forcing
    # the mass reference unrealistically close to dry mass.
    nominal_tli_thrust = 350.0  # kN

    for k in range(K_TLI_START, K_TRANSFER_START):
        dt = DT[k]
        tangent = v_ref[:, k] / max(np.linalg.norm(v_ref[:, k]), 1e-12)
        thrust_ref[:, k] = nominal_tli_thrust * tangent

        a = gravity(r_ref[:, k], TIME[k]) + thrust_ref[:, k] / mass_ref[k]

        r_ref[:, k + 1] = (
            r_ref[:, k] + dt * v_ref[:, k] + 0.5 * dt**2 * a
        )
        v_ref[:, k + 1] = v_ref[:, k] + dt * a

        mass_ref[k + 1] = mass_ref[k] - (
            dt * nominal_tli_thrust / (ISP_TLI * G0)
        )

    # -------------------------------------------------------------------------
    # C) Translunar transfer reference to a descent gate near the Moon.
    # -------------------------------------------------------------------------
    t_stage = TIME[K_DESCENT_START]
    r_moon_stage, v_moon_stage = moon_state(t_stage)

    stage_altitude = 120.0  # km
    stage_lateral = -180.0  # km

    r_stage = (
        r_moon_stage
        + (R_M + stage_altitude) * n_land
        + stage_lateral * t_land
    )

    p0 = r_ref[:, K_TRANSFER_START]
    v_depart = v_ref[:, K_TRANSFER_START]
    t0_hat = v_depart / max(np.linalg.norm(v_depart), 1e-12)
    p3 = r_stage

    chord = np.linalg.norm(p3 - p0)
    p1 = p0 + 0.20 * chord * t0_hat

    # Final Bezier tangent roughly follows Moon inertial motion so that the
    # descent gate does not begin with an enormous Moon-relative velocity.
    transfer_duration = TIME[K_DESCENT_START] - TIME[K_TRANSFER_START]
    p2_target = p3 - (transfer_duration / 3.0) * v_moon_stage
    max_p2_offset = 0.28 * chord
    d2 = p3 - p2_target
    if np.linalg.norm(d2) > max_p2_offset:
        d2 = d2 / np.linalg.norm(d2) * max_p2_offset
    p2 = p3 - d2

    t0_transfer = TIME[K_TRANSFER_START]
    tf_transfer = TIME[K_DESCENT_START]

    for k in range(K_TRANSFER_START, K_DESCENT_START + 1):
        s = (TIME[k] - t0_transfer) / (tf_transfer - t0_transfer)
        r_ref[:, k] = cubic_bezier(p0, p1, p2, p3, s)

    # Velocity for the transfer geometry. This is a reference only.
    for axis in range(3):
        v_ref[axis, K_TRANSFER_START:K_DESCENT_START + 1] = np.gradient(
            r_ref[axis, K_TRANSFER_START:K_DESCENT_START + 1],
            TIME[K_TRANSFER_START:K_DESCENT_START + 1],
            edge_order=2,
        )

    # -------------------------------------------------------------------------
    # D) Moon-relative descent reference.
    # -------------------------------------------------------------------------
    # The SAME smooth q(s) is used for altitude and lateral displacement.
    # Therefore |lateral| / altitude = 180/120 = 1.5 < tan(70 deg), so the
    # entire initial descent reference lies inside the landing cone.
    descent_duration = TIME[N] - TIME[K_DESCENT_START]
    H0 = stage_altitude
    L0 = stage_lateral

    for k in range(K_DESCENT_START, N + 1):
        s = (TIME[k] - TIME[K_DESCENT_START]) / descent_duration
        w = smoothstep5(s)
        q = 1.0 - w
        dq_dt = -smoothstep5_derivative(s) / descent_duration

        r_moon_k, v_moon_k = moon_state(TIME[k])

        rel_vec = H0 * n_land + L0 * t_land
        # Quintic position decay plus a Hermite terminal-velocity term.  The
        # latter produces a deliberate angled, moderately firm touchdown
        # instead of forcing the reference to settle vertically at zero speed.
        h11 = s**3 - s**2
        dh11_dt = (3.0 * s**2 - 2.0 * s) / descent_duration
        r_ref[:, k] = (
            r_moon_k + R_M * n_land + q * rel_vec
            + h11 * descent_duration * v_touch_target
        )
        v_ref[:, k] = (
            v_moon_k + dq_dt * rel_vec
            + dh11_dt * descent_duration * v_touch_target
        )

    # Enforce exact terminal reference state.
    r_ref[:, N] = r_land_final
    v_ref[:, N] = v_moon_final + v_touch_target
    v_ref[:, 0] = v0

    # -------------------------------------------------------------------------
    # E) Nominal thrust reference.
    # -------------------------------------------------------------------------
    # TLI reference was already set. MCC remains zero. Descent starts gently
    # and ramps up late, keeping the reference mass realistic.
    for k in range(K_DESCENT_START, N):
        s = (k - K_DESCENT_START) / max(1, N - K_DESCENT_START - 1)
        vertical = 3.0 + 18.0 * s**4
        lateral_brake = 2.0 * (1.0 - s)**2
        thrust_ref[:, k] = vertical * n_land - lateral_brake * t_land

    # -------------------------------------------------------------------------
    # F) Consistent mass reference including stage separation.
    # -------------------------------------------------------------------------
    mass_ref[:] = MASS_INITIAL
    for k in range(N):
        sigma = np.linalg.norm(thrust_ref[:, k])
        propellant = DT[k] * sigma / (phase_isp(k) * G0)
        stage_drop = STAGE_DROP_AT_DESCENT if k == K_DESCENT_START - 1 else 0.0
        mass_ref[k + 1] = mass_ref[k] - propellant - stage_drop
        mass_ref[k + 1] = max(mass_ref[k + 1], MASS_DRY + 300.0)

    return r_ref, v_ref, thrust_ref, mass_ref


r_ref, v_ref, thrust_ref, mass_ref = make_initial_reference()



