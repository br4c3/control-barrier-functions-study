def create_landing_local_animation():
    """
    Unified lunar powered-descent and landing view from the surface.

    The animation begins at the descent gate and follows the vehicle all the
    way to touchdown.  A smooth landing-site tracking zoom replaces the old
    separate Moon-context descent camera.

    Local coordinates:
        X = East [km]
        Y = North [km]
        Z = Up / altitude [km]
    """
    # Use the complete powered-descent interval; this view now also covers the
    # portion previously shown by the separate Moon-context camera.
    descent_time = TIME[K_DESCENT_START:]

    e_up = unit_vector(n_land)
    e_east = unit_vector(t_land)
    e_north = unit_vector(np.cross(e_up, e_east))
    B = np.vstack([e_east, e_north, e_up])

    t_start = float(descent_time[0])
    animation_time = np.linspace(t_start, T_TOTAL, LANDING_FRAMES)

    R_abs = interp_rows(R_solution, TIME, animation_time)
    V_abs = interp_rows(V_solution, TIME, animation_time)
    T_abs = interp_rows(T_solution, TIME[:-1], animation_time)
    moon_anim = interp_rows(moon_positions, TIME, animation_time)
    M_anim = interp_rows(M_solution, TIME, animation_time)
    prop_anim = np.interp(animation_time, TIME, PROP_CUM_NODES)
    moon_vel = np.vstack([moon_state(t)[1] for t in animation_time]).T

    local_pos = np.zeros_like(R_abs)
    local_vel = np.zeros_like(V_abs)
    local_thrust = np.zeros_like(T_abs)

    for i in range(len(animation_time)):
        landing_abs_i = moon_anim[:, i] + R_M * n_land
        local_pos[:, i] = B @ (R_abs[:, i] - landing_abs_i)
        local_vel[:, i] = B @ (V_abs[:, i] - moon_vel[:, i])
        local_thrust[:, i] = B @ T_abs[:, i]

    # ------------------------------------------------------------------
    # Initial field of view contains the entire powered descent.  update()
    # progressively tightens it around the vehicle and landing site.
    # ------------------------------------------------------------------
    max_x = max(float(np.max(np.abs(local_pos[0]))), 3.0)
    max_y = max(float(np.max(np.abs(local_pos[1]))), 3.0)
    max_alt = max(float(np.max(local_pos[2])), 5.0)

    x_half = 1.20 * max_x
    y_half = 1.20 * max_y
    z_top = 1.08 * max_alt
    z_bottom = -0.05

    # Keep a little surface context even for a nearly vertical solution.
    x_half = max(x_half, 8.0)
    y_half = max(y_half, 8.0)
    z_top = max(z_top, GROUND_VIEW_START_ALT_KM * 1.02)

    patch_half = max(15.0, 1.15 * max(x_half, y_half))
    Xs, Ys, Zs = lunar_surface_patch(patch_half, n=65)

    fig = plt.figure(figsize=(11.5, 8.5))
    ax = fig.add_subplot(111, projection="3d")

    # The landing-site tangent plane is the visual floor at local Z=0.  This
    # matches the altitude and landing-cone constraints used by the optimizer.
    ax.plot_surface(
        Xs, Ys, Zs,
        color="#777777",
        alpha=0.78,
        edgecolor="#9a9a9a",
        linewidth=0.22,
        antialiased=True,
        shade=True,
    )

    # Entire final landing path is shown faintly as context.
    ax.plot(
        local_pos[0], local_pos[1], local_pos[2],
        linewidth=1.1,
        alpha=0.22,
        label="Final landing trajectory",
    )

    progress_line, = ax.plot([], [], [], linewidth=2.8, label="Flight path")
    spacecraft_point, = ax.plot([], [], [], marker="o", markersize=4, linestyle="None")
    landing_marker, = ax.plot(
        [0.0], [0.0], [0.0],
        marker="*", markersize=14, linestyle="None", label="Landing site"
    )

    # A small landing-pad ring on the surface makes touchdown easy to see.
    pad_theta = np.linspace(0.0, 2.0 * np.pi, 100)
    pad_r = min(0.8, 0.06 * max(x_half, y_half))
    ax.plot(
        pad_r * np.cos(pad_theta),
        pad_r * np.sin(pad_theta),
        np.zeros_like(pad_theta),
        linewidth=1.5,
        label="Landing pad",
    )

    # Landing cone constraint shown as a wireframe corridor.  Feasible vehicle
    # positions lie inside this cone: horizontal error <= tan(angle) * altitude.
    guide_alt = np.linspace(0.0, z_top, 60)
    guide_rad = np.tan(LANDING_CONE_ANGLE) * guide_alt
    guide_mask = guide_rad <= 0.95 * max(x_half, y_half)
    guide_alt = guide_alt[guide_mask]
    guide_rad = guide_rad[guide_mask]
    if len(guide_alt) > 1:
        cone_theta = np.linspace(0.0, 2.0 * np.pi, 25)
        cone_R, cone_Theta = np.meshgrid(guide_rad, cone_theta)
        cone_Z = np.broadcast_to(guide_alt, cone_R.shape)
        ax.plot_wireframe(
            cone_R * np.cos(cone_Theta),
            cone_R * np.sin(cone_Theta),
            cone_Z,
            rstride=4,
            cstride=10,
            color="tab:orange",
            linewidth=0.65,
            alpha=0.32,
            label=f"Landing cone ({np.degrees(LANDING_CONE_ANGLE):.0f} deg)",
        )

    # ------------------------------------------------------------------
    # Ground observer camera.
    # Low elevation makes the scene look from near the lunar surface rather
    # than from above.  This stays unchanged for the whole animation.
    # ------------------------------------------------------------------
    initial_horizontal = local_pos[:2, 0]
    if np.linalg.norm(initial_horizontal) > 1.0e-8:
        approach_azimuth = np.degrees(np.arctan2(initial_horizontal[1], initial_horizontal[0]))
        camera_azim = approach_azimuth + 155.0
    else:
        camera_azim = -55.0

    ax.view_init(elev=18.0, azim=camera_azim)
    ax.set_proj_type("persp", focal_length=0.9)

    ax.set_xlim(-x_half, x_half)
    ax.set_ylim(-y_half, y_half)
    ax.set_zlim(z_bottom, z_top)
    ax.set_box_aspect((2.0 * x_half, 2.0 * y_half, 1.45 * z_top))
    ax.zaxis.set_pane_color((0.0, 0.0, 0.0, 0.0))

    ax.set_xlabel("Local East [km]")
    ax.set_ylabel("Local North [km]")
    ax.set_zlabel("Altitude [km]")
    ax.legend(loc="upper left")

    telemetry = ax.text2D(
        0.02, 0.02, "",
        transform=ax.transAxes,
        va="bottom",
        family="monospace",
    )

    fixed_camera_note = ax.text2D(
        0.71, 0.02,
        "POWERED DESCENT + LANDING\nTRACKING GROUND CAMERA",
        transform=ax.transAxes,
        va="bottom",
        ha="left",
        family="monospace",
    )

    dynamic_artists = []

    def clear_dynamic():
        while dynamic_artists:
            artist = dynamic_artists.pop()
            try:
                artist.remove()
            except (ValueError, AttributeError):
                pass

    # Rocket display size is fixed for the whole ground-view clip.
    rocket_length = float(np.clip(0.055 * z_top, 0.75, 1.75))
    rocket_radius = 0.17 * rocket_length

    def update(frame_idx):
        clear_dynamic()

        ti = animation_time[frame_idx]
        p = local_pos[:, frame_idx]
        v = local_vel[:, frame_idx]
        thrust_vec = local_thrust[:, frame_idx]
        body_axis = unit_vector(thrust_vec, fallback=-v)

        # Keep both vehicle and landing point in frame, then smoothly tighten
        # to the flat lunar floor as the remaining distance approaches zero.
        remaining_distance = float(np.linalg.norm(p))
        initial_distance = max(float(np.linalg.norm(local_pos[:, 0])), 1.0)
        zoom_fraction = np.clip(remaining_distance / initial_distance, 0.0, 1.0)

        # Hold the wide composition longer.  The previous smoothstep closed in
        # too quickly and could crop the vehicle above the frame during lunar
        # arrival.  The square root gives more screen space through mid-descent.
        smooth_zoom = np.sqrt(zoom_fraction)
        view_half = 8.0 + (max(x_half, y_half) - 8.0) * smooth_zoom
        view_half = max(view_half, 0.78 * np.linalg.norm(p[:2]) + 2.0)
        view_center_xy = (0.32 + 0.13 * smooth_zoom) * p[:2]
        view_top = 5.0 + (z_top - 5.0) * smooth_zoom
        view_top = max(view_top, 1.18 * max(p[2], 0.0) + 2.0)
        ax.set_xlim(view_center_xy[0] - view_half, view_center_xy[0] + view_half)
        ax.set_ylim(view_center_xy[1] - view_half, view_center_xy[1] + view_half)
        ax.set_zlim(z_bottom, view_top)
        ax.set_box_aspect((2.0 * view_half, 2.0 * view_half, 1.45 * view_top))
        camera_elev = 8.0 + 10.0 * smooth_zoom
        ax.view_init(elev=camera_elev, azim=camera_azim)

        body, nose, _ = rocket_mesh(p, body_axis, rocket_length, rocket_radius)
        Xb, Yb, Zb = body
        Xn, Yn, Zn = nose

        body_artist = ax.plot_surface(
            Xb, Yb, Zb,
            alpha=0.98,
            linewidth=0,
            antialiased=False,
        )
        nose_artist = ax.plot_surface(
            Xn, Yn, Zn,
            alpha=0.98,
            linewidth=0,
            antialiased=False,
        )
        dynamic_artists.extend([body_artist, nose_artist])

        # +T arrow and -T exhaust flame.  Their DISPLAY scale varies with
        # thrust magnitude, but the camera and axes do not move.
        add_thrust_visuals(
            ax,
            p,
            thrust_vec,
            body_axis,
            rocket_length,
            rocket_radius,
            ti,
            dynamic_artists,
            arrow_scale=2.4,
            flame_scale=2.5,
            min_arrow_fraction=0.22,
        )

        progress_line.set_data(
            local_pos[0, :frame_idx + 1],
            local_pos[1, :frame_idx + 1],
        )
        progress_line.set_3d_properties(local_pos[2, :frame_idx + 1])
        spacecraft_point.set_data([p[0]], [p[1]])
        spacecraft_point.set_3d_properties([p[2]])

        thrust_kn = np.linalg.norm(thrust_vec)
        speed_ms = np.linalg.norm(v) * 1000.0
        horizontal_ms = np.linalg.norm(v[:2]) * 1000.0
        vertical_ms = v[2] * 1000.0
        altitude_km = max(p[2], 0.0)
        horizontal_km = np.linalg.norm(p[:2])
        cone_limit_km = np.tan(LANDING_CONE_ANGLE) * altitude_km
        cone_margin_km = cone_limit_km - horizontal_km

        descent_frac = np.clip(
            (ti - TIME[K_DESCENT_START])
            / max(T_TOTAL - TIME[K_DESCENT_START], 1.0),
            0.0,
            1.0,
        )
        speed_limit_ms = (
            2.5 * (1.0 - descent_frac)**1.3 + 0.030
        ) * 1000.0
        if descent_frac >= 0.75:
            terminal_frac = (descent_frac - 0.75) / 0.25
            down_limit_ms = (
                0.080 * (1.0 - terminal_frac) + TOUCHDOWN_SPEED_MAX
            ) * 1000.0
            horizontal_limit_ms = (
                0.050 * (1.0 - terminal_frac) + TOUCHDOWN_HORIZONTAL_MAX
            ) * 1000.0
        else:
            down_limit_ms = speed_limit_ms
            horizontal_limit_ms = speed_limit_ms

        cone_ok = cone_margin_km >= -1.0e-6
        speed_ok = speed_ms <= speed_limit_ms + 1.0e-6
        terminal_ok = (
            -vertical_ms <= down_limit_ms + 1.0e-6
            and horizontal_ms <= horizontal_limit_ms + 1.0e-6
        )

        # Ring at the current altitude makes the instantaneous position bound
        # readable without having to infer it from the full cone wireframe.
        if cone_limit_km <= 1.5 * max(x_half, y_half):
            ring_theta = np.linspace(0.0, 2.0 * np.pi, 80)
            constraint_ring, = ax.plot(
                cone_limit_km * np.cos(ring_theta),
                cone_limit_km * np.sin(ring_theta),
                np.full_like(ring_theta, altitude_km),
                color="tab:green" if cone_ok else "tab:red",
                linewidth=1.8,
                alpha=0.85,
            )
            dynamic_artists.append(constraint_ring)

        telemetry.set_text(
            f"elapsed       {(ti - t_start):8.1f} s\n"
            f"altitude      {altitude_km:8.3f} km\n"
            f"horizontal    {horizontal_km:8.3f} km\n"
            f"speed         {speed_ms:8.2f} m/s\n"
            f"horizontal v  {horizontal_ms:8.2f} m/s\n"
            f"vertical v    {vertical_ms:8.2f} m/s\n"
            f"thrust        {thrust_kn:8.2f} kN\n"
            f"cone margin   {cone_margin_km:8.3f} km  {'OK' if cone_ok else 'VIOL'}\n"
            f"speed limit   {speed_limit_ms:8.2f} m/s  {'OK' if speed_ok else 'VIOL'}\n"
            f"down limit    {down_limit_ms:8.2f} m/s\n"
            f"horiz limit   {horizontal_limit_ms:8.2f} m/s  "
            f"{'OK' if terminal_ok else 'VIOL'}\n"
            f"mass          {M_anim[frame_idx]:8.0f} kg\n"
            f"propellant    {prop_anim[frame_idx]:8.0f} kg"
        )

        ax.set_title(
            "Lunar powered descent + landing — ground tracking view\n"
            "flat surface | arrow = +thrust | flame = exhaust (-thrust)"
        )

        return [
            progress_line,
            spacecraft_point,
            landing_marker,
            telemetry,
            fixed_camera_note,
            *dynamic_artists,
        ]

    anim = FuncAnimation(
        fig,
        update,
        frames=len(animation_time),
        interval=1000.0 / ANIMATION_FPS,
        blit=False,
        repeat=False,
    )
    return fig, anim


