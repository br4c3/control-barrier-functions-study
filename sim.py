def interp_rows(data, t_old, t_new):
    """Interpolate 1-D or row-wise 2-D data onto a new time grid."""
    data = np.asarray(data)
    if data.ndim == 1:
        return np.interp(t_new, t_old, data)
    return np.vstack([
        np.interp(t_new, t_old, data[i])
        for i in range(data.shape[0])
    ])


def unit_vector(v, fallback=None):
    v = np.asarray(v, dtype=float)
    n = np.linalg.norm(v)
    if n > 1.0e-12:
        return v / n

    if fallback is not None:
        fallback = np.asarray(fallback, dtype=float)
        nf = np.linalg.norm(fallback)
        if nf > 1.0e-12:
            return fallback / nf

    return np.array([0.0, 0.0, 1.0])


def body_basis(axis):
    """Return two orthonormal vectors perpendicular to axis."""
    axis = unit_vector(axis)
    helper = np.array([0.0, 0.0, 1.0])
    if abs(np.dot(axis, helper)) > 0.95:
        helper = np.array([0.0, 1.0, 0.0])

    e1 = unit_vector(np.cross(axis, helper))
    e2 = unit_vector(np.cross(axis, e1))
    return e1, e2


def cylinder_mesh(center, axis, length, radius, n_theta=16):
    """Create a cylindrical rocket body aligned with axis."""
    axis = unit_vector(axis)
    e1, e2 = body_basis(axis)

    theta = np.linspace(0.0, 2.0 * np.pi, n_theta)
    axial = np.array([-0.5 * length, 0.5 * length])

    X = np.zeros((2, n_theta))
    Y = np.zeros((2, n_theta))
    Z = np.zeros((2, n_theta))

    for j, s in enumerate(axial):
        ring_center = center + s * axis
        for i, th in enumerate(theta):
            p = (
                ring_center
                + radius * np.cos(th) * e1
                + radius * np.sin(th) * e2
            )
            X[j, i], Y[j, i], Z[j, i] = p

    return X, Y, Z


def cone_mesh(tip, axis, length, radius, n_theta=16):
    """Create a cone whose pointed tip is 'tip' and axis points toward the tip."""
    axis = unit_vector(axis)
    e1, e2 = body_basis(axis)

    theta = np.linspace(0.0, 2.0 * np.pi, n_theta)
    X = np.zeros((2, n_theta))
    Y = np.zeros((2, n_theta))
    Z = np.zeros((2, n_theta))

    base_center = tip - length * axis
    for i, th in enumerate(theta):
        p = (
            base_center
            + radius * np.cos(th) * e1
            + radius * np.sin(th) * e2
        )
        X[0, i], Y[0, i], Z[0, i] = p
        X[1, i], Y[1, i], Z[1, i] = tip

    return X, Y, Z


def flame_mesh(nozzle, exhaust_direction, length, radius, n_theta=14):
    """Cone with wide base at nozzle and pointed tip downstream."""
    exhaust_direction = unit_vector(exhaust_direction)
    e1, e2 = body_basis(exhaust_direction)
    theta = np.linspace(0.0, 2.0 * np.pi, n_theta)
    tip = nozzle + length * exhaust_direction

    X = np.zeros((2, n_theta))
    Y = np.zeros((2, n_theta))
    Z = np.zeros((2, n_theta))

    for i, th in enumerate(theta):
        base = (
            nozzle
            + radius * np.cos(th) * e1
            + radius * np.sin(th) * e2
        )
        X[0, i], Y[0, i], Z[0, i] = base
        X[1, i], Y[1, i], Z[1, i] = tip

    return X, Y, Z


def rocket_mesh(position, direction, total_length, body_radius):
    """Return body/nose mesh plus rear nozzle position."""
    direction = unit_vector(direction)

    body_length = 0.76 * total_length
    nose_length = 0.24 * total_length

    body_center = position - 0.12 * total_length * direction
    nose_tip = position + 0.50 * total_length * direction
    nozzle = position - 0.50 * total_length * direction

    body = cylinder_mesh(
        body_center,
        direction,
        body_length,
        body_radius,
    )
    nose = cone_mesh(
        nose_tip,
        direction,
        nose_length,
        body_radius,
    )
    return body, nose, nozzle


def sphere_mesh(center, radius, n_u=22, n_v=12):
    u = np.linspace(0.0, 2.0 * np.pi, n_u)
    v = np.linspace(0.0, np.pi, n_v)
    X = center[0] + radius * np.outer(np.cos(u), np.sin(v))
    Y = center[1] + radius * np.outer(np.sin(u), np.sin(v))
    Z = center[2] + radius * np.outer(np.ones_like(u), np.cos(v))
    return X, Y, Z


def lunar_surface_patch(half_width, n=45):
    """Flat landing-site tangent plane used as the local lunar ground."""
    x = np.linspace(-half_width, half_width, n)
    y = np.linspace(-half_width, half_width, n)
    X, Y = np.meshgrid(x, y)
    Z = np.zeros_like(X)
    return X, Y, Z


def set_3d_bounds(ax, points, padding_fraction=0.10):
    points = np.asarray(points)
    mins = points.min(axis=1)
    maxs = points.max(axis=1)
    span = np.max(maxs - mins)
    pad = max(span * padding_fraction, 1.0)

    ax.set_xlim(mins[0] - pad, maxs[0] + pad)
    ax.set_ylim(mins[1] - pad, maxs[1] + pad)
    ax.set_zlim(mins[2] - pad, maxs[2] + pad)
    ax.set_box_aspect((
        maxs[0] - mins[0] + 2 * pad,
        maxs[1] - mins[1] + 2 * pad,
        maxs[2] - mins[2] + 2 * pad,
    ))


def phase_name(t):
    if t < TIME[K_TLI_START]:
        return "Earth parking orbit"
    if t < TIME[K_TRANSFER_START]:
        return "TLI burn"
    if t < TIME[K_DESCENT_START]:
        return "Translunar transfer / MCC"
    return "Lunar powered descent"


def phase_tmax(t):
    if t < TIME[K_TLI_START]:
        return 1.0
    if t < TIME[K_TRANSFER_START]:
        return TMAX_TLI
    if t < TIME[K_DESCENT_START]:
        return TMAX_MCC
    return TMAX_DESCENT


def thrust_fraction(thrust_vector, t):
    return float(np.clip(
        np.linalg.norm(thrust_vector) / max(phase_tmax(t), 1.0e-9),
        0.0,
        1.0,
    ))


def add_thrust_visuals(
    ax,
    position,
    thrust_vector,
    body_axis,
    rocket_length,
    rocket_radius,
    t,
    artist_list,
    arrow_scale=1.4,
    flame_scale=1.7,
    min_arrow_fraction=0.18,
):
    """Add +T force arrow and -T exhaust flame. Artists are removable next frame."""
    thrust_mag = np.linalg.norm(thrust_vector)
    if thrust_mag < 1.0e-6:
        return

    t_dir = unit_vector(thrust_vector, fallback=body_axis)
    frac = thrust_fraction(thrust_vector, t)

    # +T force arrow from vehicle center.
    # Keep low-thrust navigation corrections legible.  Magnitude still changes
    # the arrow length, but the display does not collapse to a nearly invisible
    # mark at the Earth-Moon overview scale.
    display_frac = min_arrow_fraction + (1.0 - min_arrow_fraction) * frac
    arrow_length = rocket_length * arrow_scale * display_frac
    q = ax.quiver(
        position[0], position[1], position[2],
        t_dir[0], t_dir[1], t_dir[2],
        length=arrow_length,
        normalize=True,
        color="tab:red",
        linewidth=3.2,
        arrow_length_ratio=0.26,
    )
    artist_list.append(q)

    # Exhaust leaves the nozzle opposite to thrust direction.
    nozzle = position - 0.50 * rocket_length * unit_vector(body_axis)
    flame_length = rocket_length * flame_scale * frac
    flame_radius = rocket_radius * (0.55 + 0.45 * frac)

    if flame_length > 1.0e-5:
        Xf, Yf, Zf = flame_mesh(
            nozzle,
            -t_dir,
            flame_length,
            flame_radius,
        )
        flame = ax.plot_surface(
            Xf, Yf, Zf,
            alpha=0.72,
            linewidth=0,
            antialiased=False,
        )
        artist_list.append(flame)


def cumulative_propellant_nodes():
    prop = np.zeros(N + 1)
    for k in range(N):
        prop[k + 1] = prop[k] + (
            DT[k] * SIGMA_solution[k]
            / (phase_isp(k) * G0)
        )
    return prop


